package models

// RaidRules are raid-rules.toml: the early-death and mass-kill thresholds, the soak window, the raid cooldowns and
// each boss's phase triggers (by boss name as ENCOUNTER_START gives it).
type RaidRules struct {
	Deaths struct {
		First                 int     `toml:"first"`
		BeforeWipeSeconds     float64 `toml:"before_wipe_seconds"`
		MassKillPlayers       int     `toml:"mass_kill_players"`
		MassKillWindowSeconds float64 `toml:"mass_kill_window_seconds"`
	} `toml:"deaths"`
	Soaks struct {
		WindowMS int64 `toml:"window_ms"`
	} `toml:"soaks"`
	Cooldowns struct {
		Names      []string `toml:"names"`
		HealerOnly []string `toml:"healer_only"` // cooldowns that count only from a healer (other specs share the name)
	} `toml:"cooldowns"`
	Consumables struct {
		Vantus             []string `toml:"vantus"`              // a Vantus Rune's name patterns, checked with flask and food
		VantusIDs          []int    `toml:"vantus_ids"`          // Vantus Rune auras the log never names, by ID
		VantusDifficulties []string `toml:"vantus_difficulties"` // the difficulties the raid's rune works in ("Heroic")
	} `toml:"consumables"`
	Tier struct {
		Sets []int `toml:"sets"` // the raid's class tier sets, by Wowhead item-set ID (cmd/raidref reads them)
	} `toml:"tier"`
	Suggestions SuggestionRules           `toml:"suggestions"`
	Phases      map[string][]PhaseTrigger `toml:"phases"`
}

// ItemSet is a Wowhead item set: its items and the specs that can wear them.
type ItemSet struct {
	Items []int
	Specs []int
}

// SuggestionRules are raid-rules.toml's [suggestions]: how many "Fix next pull" lines, the damage spike's window,
// when an add's life or the damage into a unit to burst is worth a line against tonight's best pull, how long a pull
// is before Bloodlust and combat potions are expected, how long a debuff sits before its dispel was slow, and how
// close two raid cooldowns are to be stacked.
type SuggestionRules struct {
	Most                   int     `toml:"most"`
	SpikeSeconds           float64 `toml:"spike_seconds"`
	AddsLonger             float64 `toml:"adds_longer"`
	PriorityBelow          float64 `toml:"priority_below"`
	LustAfterSeconds       float64 `toml:"lust_after_seconds"`
	DispelSlowSeconds      float64 `toml:"dispel_slow_seconds"`
	CooldownOverlapSeconds float64 `toml:"cooldown_overlap_seconds"`
}

// PhaseTrigger is a boss phase after phase 1, numbered as Warcraft Logs numbers it, and the event and spell ID that
// start it (none when not found yet).
type PhaseTrigger struct {
	ID           int    `toml:"id"`
	Event        string `toml:"event"`
	Spell        int    `toml:"spell"`
	Intermission bool   `toml:"intermission"`
}

// RaidReference is reference/raid-bosses.json: a raid's boss mechanics for the raid overview, generated by
// cmd/raidref from Wowhead's boss cheat sheets and reference/raid-mechanics.toml, never typed by hand.
type RaidReference struct {
	Raid    string              `json:"raid"`
	Sources map[string]string   `json:"sources"`
	Bosses  map[string]RaidBoss `json:"bosses"`         // by boss name as ENCOUNTER_START gives it
	Tier    map[string][]int    `json:"tier,omitempty"` // class ("DeathKnight") -> its tier set's item IDs
}

// RaidBoss is one boss's NPC IDs and mechanics by kind: spell IDs to dodge (damage), soak (damage), dispel (debuffs)
// and interrupt (casts), debuffs whose stacks matter (spell ID to the stacks that are too many, 0 when the guide
// gives no number), units to burst (names), and from the curated file: how many raiders each soak wants, auras
// raiders take by picking something up, debuffs whose removal sets off a raid-wide effect, and what spawns each add.
type RaidBoss struct {
	Name      string           `json:"name"`
	Guide     string           `json:"guide"`
	NPCs      []int            `json:"npcs"`
	Health    []int            `json:"health,omitempty"` // the NPCs whose health is the boss's; empty: see service bossUnits
	Avoidable []int            `json:"avoidable"`
	Soak      []int            `json:"soak"`
	Soakers   map[int]int      `json:"soakers,omitempty"` // soak spell ID -> raiders wanted in each (0 or missing: everyone)
	Dispel    []int            `json:"dispel"`
	MustStop  []int            `json:"mustStop"`
	Stacks    map[int]int      `json:"stacks"`
	Priority  []string         `json:"priority"`
	Pickups   []RaidPickupRule `json:"pickups,omitempty"`
	Breaks    []RaidBreakRule  `json:"breaks,omitempty"`
	Spawns    []RaidSpawnRule  `json:"spawns,omitempty"`
	Checked   string           `json:"checked,omitempty"` // how the curated mechanics were checked; empty: not curated
	Sources   []string         `json:"sources,omitempty"`
	Maps      []RaidMap        `json:"maps"` // the rooms the boss is fought in
}

// RaidMechanics is reference/raid-mechanics.toml: the hand-kept mechanics of each boss (by boss name as
// ENCOUNTER_START gives it), which cmd/raidref merges into reference/raid-bosses.json.
type RaidMechanics struct {
	Raid   string                 `toml:"raid"` // Wowhead's slug of the raid it's for
	Bosses map[string]CuratedBoss `toml:"bosses"`
}

// CuratedBoss is one boss's hand-kept mechanics (RaidBoss has what each list holds) and how they were checked.
type CuratedBoss struct {
	Checked   string           `toml:"checked"`
	Sources   []string         `toml:"sources"`
	Health    []int            `toml:"health"`
	Avoidable []int            `toml:"avoidable"`
	Dispel    []int            `toml:"dispel"`
	MustStop  []int            `toml:"must_stop"`
	Stacks    map[string]int   `toml:"stacks"` // TOML keys are strings: spell ID -> stacks that are too many
	Priority  []string         `toml:"priority"`
	Soaks     []CuratedSoak    `toml:"soaks"`
	Pickups   []RaidPickupRule `toml:"pickups"`
	Breaks    []RaidBreakRule  `toml:"breaks"`
	Spawns    []RaidSpawnRule  `toml:"spawns"`
}

// CuratedSoak is a soak's damage spell and how many raiders each one wants (0: everyone).
type CuratedSoak struct {
	Spell   int `toml:"spell"`
	Soakers int `toml:"soakers"`
}

// RaidPickupRule is an aura a raider takes on by picking something up (an egg), what it is, the difficulties it
// happens on (none: all), and for something every living raider should pick up, Expect: the enemy spell it's needed
// for (Extinguish), whose cast ends each wave; who lacks the aura then didn't pick one up.
type RaidPickupRule struct {
	Aura         int      `json:"aura" toml:"aura"`
	Name         string   `json:"name" toml:"name"`
	Difficulties []string `json:"difficulties,omitempty" toml:"difficulties"`
	Expect       int      `json:"expect,omitempty" toml:"expect"`
}

// RaidBreakRule is a debuff whose removal (a raider breaking a tether) sets off Effect, an aura on the raid, within
// WithinMS.
type RaidBreakRule struct {
	Aura     int   `json:"aura" toml:"aura"`
	Effect   int   `json:"effect" toml:"effect"`
	WithinMS int64 `json:"withinMS" toml:"within_ms"`
}

// RaidSpawnRule is what makes an add of a name appear: Cause, a spell cast by an enemy or landing on raiders, at most
// WithinMS before the add is first seen. With Lost, the add is the raider's whose Lost aura came off as Cause landed
// on them (an egg breaking), one add each.
type RaidSpawnRule struct {
	Add      string `json:"add" toml:"add"`
	Cause    int    `json:"cause" toml:"cause"`
	Lost     int    `json:"lost,omitempty" toml:"lost"`
	WithinMS int64  `json:"withinMS" toml:"within_ms"`
}

// RaidMap is a raid room's map (the combat log's uiMapID) and its edges in the log's yards: x runs north (MaxX at the
// top), y west (MaxY at the left), as the game's UiMapAssignment gives them.
type RaidMap struct {
	UIMapID int     `json:"uiMapID"`
	MinX    float64 `json:"minX"`
	MaxX    float64 `json:"maxX"`
	MinY    float64 `json:"minY"`
	MaxY    float64 `json:"maxY"`
}

// RaidGuide is a Wowhead boss cheat sheet: the boss's name, the page and its mechanic lines.
type RaidGuide struct {
	Name  string
	URL   string
	Lines []RaidGuideLine
}

// RaidGuideLine is one mechanic line of a Wowhead boss cheat sheet: the spells it tags and its words, read to sort
// the mechanic by kind and never stored.
type RaidGuideLine struct {
	Spells []int
	Text   string
}

// RaidPull is one raid pull as the overview shows it: the boss, difficulty and pull number tonight, how far it got,
// the deaths, what went wrong by kind of mechanic, the meters and the cooldowns, and the pulls it's compared with.
type RaidPull struct {
	Start      int64          `json:"start"`
	End        int64          `json:"end"`
	Night      string         `json:"night" example:"2026-11-03"` // the raid night: the start's date, before 6 am counting as the day before
	Boss       string         `json:"boss"`
	Difficulty string         `json:"difficulty" enums:"LFR,Normal,Heroic,Mythic"`
	Number     int            `json:"number"` // the pull's number on this boss and difficulty tonight, from the pulls known when it's read
	DurationMS int64          `json:"durationMS"`
	Kill       bool           `json:"kill"`
	BossPct    float64        `json:"bossPct"` // the boss's health left, 0-100; -1 without advanced logging
	Phase      string         `json:"phase"`   // the last phase reached ("P2"); empty for a boss without phase triggers
	Players    []string       `json:"players"`
	Deaths     []RaidDeath    `json:"deaths"`
	MassKills  []MassKill     `json:"massKills"`
	Avoidable  []RaidHits     `json:"avoidable"`
	Soaks      []RaidSoak     `json:"soaks"`
	Pickups    []RaidPickup   `json:"pickups"` // what raiders picked up (eggs), each wave in order
	Breaks     []RaidBreak    `json:"breaks"`  // tethers raiders broke, in order
	Stacks     []RaidStacks   `json:"stacks"`
	Dispels    []KeyDispel    `json:"dispels"` // slowest first
	WentOff    []KeyStop      `json:"wentOff"` // must-stop casts that finished
	Adds       []RaidAdd      `json:"adds"`
	Priority   []RaidPriority `json:"priority"`
	Meter      KeyMeter       `json:"meter"`
	Lusts      []int64        `json:"lusts"`     // when Bloodlust landed, ms into the pull
	Cooldowns  []KeyCast      `json:"cooldowns"` // raid cooldowns and combat potions, in order
	Maps       []RaidMap      `json:"maps"`      // the boss's rooms for the replay, from the reference file
	Lanes      []RaidLane     `json:"lanes"`
	// Suggestions is what to fix on the next pull, most important first, worked out when the pull is read so it's
	// compared with the best pull as of then.
	Suggestions []string         `json:"suggestions"`
	Comparisons *RaidComparisons `json:"comparisons,omitempty"`
	// Abilities is each raider's damage, healing and casts by ability, Taken their damage taken by ability and Targets
	// their damage into each enemy, most first: missing in pulls saved before Nov 11.
	Abilities []KeyAbility `json:"abilities,omitempty"`
	Taken     []KeyHit     `json:"taken,omitempty"`
	Targets   []RaidTarget `json:"targets,omitempty"`
	// The fight's lists as a key has them, for the tabs both pages show: every interrupt, must-stop cast, kick that
	// stopped nothing, dispellable debuff, damage spike and survival, potion or crowd-control button pressed, and each
	// raider's active time (%); missing in pulls saved before Nov 11.
	Interrupts  []KeyInterrupt     `json:"interrupts,omitempty"`
	Stops       []KeyStop          `json:"stops,omitempty"`
	WastedKicks []KeyCast          `json:"wastedKicks,omitempty"`
	Debuffs     []KeyDispel        `json:"debuffs,omitempty"`
	Spikes      []KeySpike         `json:"spikes,omitempty"`
	Casts       []KeyCast          `json:"casts,omitempty"`
	Activity    map[string]float64 `json:"activity,omitempty"`
	// BuffGaps is each raider's flask, food, Vantus Rune, tier bonus or raid buff missing at the pull's start (from 0)
	// and each flask, food or raid buff that came off them in the pull for a while, in order; missing before Nov 12.
	BuffGaps []RaidMissing `json:"buffGaps,omitempty"`
}

// RaidMissing is a raider without a buff ("flask", "Arcane Intellect", "2-set") from FromMS to ToMS on the pull's
// clock (ToMS is the pull's end when it never came back).
type RaidMissing struct {
	Player string `json:"player"`
	Buff   string `json:"buff"`
	FromMS int64  `json:"fromMS"`
	ToMS   int64  `json:"toMS"`
}

// RaidTarget is a raider's damage into the enemies of one name over a pull.
type RaidTarget struct {
	Player string `json:"player"`
	Target string `json:"target"`
	Damage int64  `json:"damage"`
}

// RaidDeath is a raider's death: what killed them and what was ready (the M+ death rules), whether it was early
// (before the wipe), and the last hits they took.
type RaidDeath struct {
	KeyDeath
	Early bool      `json:"early"`
	Recap []RaidHit `json:"recap"` // the last hits before the death, oldest first
}

// RaidHit is one hit a raider took: the ability, who dealt it, the amount and how long before the death.
type RaidHit struct {
	Ability  string `json:"ability"`
	Source   string `json:"source"`
	Amount   int64  `json:"amount"`
	BeforeMS int64  `json:"beforeMS"`
}

// MassKill is one ability killing several raiders within the mass-kill window.
type MassKill struct {
	Ability string `json:"ability"`
	Killed  int    `json:"killed"`
	ClockMS int64  `json:"clockMS"`
}

// RaidHits is an avoidable ability's direct hits per player, most first.
type RaidHits struct {
	Ability string        `json:"ability"`
	Players []PlayerCount `json:"players"`
}

// PlayerCount is a number for one player.
type PlayerCount struct {
	Player string `json:"player"`
	Count  int    `json:"count"`
}

// RaidSoak is a soak mechanic: how many times it came, the fewest and most raiders who took one, how many each
// wants (0: everyone, or unknown), who soaked each, and who died to it.
type RaidSoak struct {
	Ability string         `json:"ability"`
	Casts   int            `json:"casts"`
	Fewest  int            `json:"fewest"`
	Most    int            `json:"most"`
	Needed  int            `json:"needed"`
	Hits    []RaidSoakCast `json:"hits"` // missing in pulls saved before Nov 11
	Died    []string       `json:"died"`
}

// RaidSoakCast is one cast of a soak: when it first hit, and the raiders it hit.
type RaidSoakCast struct {
	ClockMS int64    `json:"clockMS"`
	Players []string `json:"players"`
}

// RaidPickup is a wave of raiders picking something up (an egg) at about the same time: when, what, who, and for
// something everyone should pick up, the living raiders who hadn't when it was needed.
type RaidPickup struct {
	ClockMS int64    `json:"clockMS"`
	Name    string   `json:"name"`
	Players []string `json:"players"`
	Missed  []string `json:"missed,omitempty"`
}

// RaidBreak is a raider breaking a tether (a debuff coming off them): when, the debuff, and the raid-wide effect it
// set off with how many raiders it hit (Effect empty when none followed).
type RaidBreak struct {
	ClockMS int64  `json:"clockMS"`
	Player  string `json:"player"`
	Aura    string `json:"aura"`
	Effect  string `json:"effect,omitempty"`
	Hit     int    `json:"hit"`
}

// RaidSpawn is one add appearing: when, and what made it (the spell and the raiders it landed on), Cause empty when
// nothing the reference names came just before.
type RaidSpawn struct {
	ClockMS int64    `json:"clockMS"`
	Cause   string   `json:"cause,omitempty"`
	Players []string `json:"players"`
}

// RaidStacks is a debuff whose stacks matter: the stacks that are too many (0 when unknown) and each player's most,
// most first.
type RaidStacks struct {
	Ability string        `json:"ability"`
	Limit   int           `json:"limit"`
	Players []PlayerCount `json:"players"`
}

// RaidAdd is one kind of add: how many showed up, died, and were still up at the end, and the longest one lived.
type RaidAdd struct {
	Name      string `json:"name"`
	Spawned   int    `json:"spawned"`
	Killed    int    `json:"killed"`
	AliveEnd  int    `json:"aliveEnd"`
	LongestMS int64  `json:"longestMS"`
	// Spawns is each one's appearance and its cause, for adds the reference says how they spawn; missing in pulls
	// saved before Nov 11.
	Spawns []RaidSpawn `json:"spawns,omitempty"`
}

// RaidPriority is the raid's damage into a unit to burst.
type RaidPriority struct {
	Target string `json:"target"`
	Damage int64  `json:"damage"`
}

// RaidComparisons are the pulls a pull is compared with: tonight's best and the best ever on the boss and
// difficulty (nil when it is that pull).
type RaidComparisons struct {
	Tonight *RaidPullSummary `json:"tonight,omitempty"`
	Ever    *RaidPullSummary `json:"ever,omitempty"`
}

// RaidPullSummary is a pull in a list: when, which boss, its number tonight, and how far it got.
type RaidPullSummary struct {
	Start      int64   `json:"start"`
	Night      string  `json:"night"`
	Boss       string  `json:"boss"`
	Difficulty string  `json:"difficulty"`
	Number     int     `json:"number"`
	DurationMS int64   `json:"durationMS"`
	Kill       bool    `json:"kill"`
	BossPct    float64 `json:"bossPct"`
	Phase      string  `json:"phase"`
}

// RaidLive is the raid as the overview shows it now: whether a pull is on (its boss and start), the last pull that
// ended, compared with the best ones, and whether the overlay shows it (between pulls, for a few minutes).
type RaidLive struct {
	Pulling      bool      `json:"pulling"`
	BetweenPulls bool      `json:"betweenPulls"`
	Boss         string    `json:"boss,omitempty"`
	Since        int64     `json:"since,omitempty"`
	Last         *RaidPull `json:"last,omitempty"`
	// Ready is who's missing a flask, food, Vantus Rune or raid buff, in a raid between pulls.
	Ready *ReadyCheck `json:"ready,omitempty"`
}

// RaidNight is one raid night's pulls, newest first.
type RaidNight struct {
	Night string            `json:"night"`
	Pulls []RaidPullSummary `json:"pulls"`
}

// RaidLane is one row of a pull's timeline: a mechanic (or the phases, deaths, Bloodlust, cooldowns, potions, an add
// kind) and each time it came up, in order.
type RaidLane struct {
	Name  string     `json:"name"`
	Kind  string     `json:"kind" enums:"phases,deaths,lust,cooldowns,potions,spike,avoidable,soak,pickups,stacks,adds"`
	Marks []RaidMark `json:"marks"`
}

// RaidMark is a moment on a lane, or a stretch when EndMS is after ClockMS (a phase, an add's life, Bloodlust or a
// raid cooldown's buff), on the pull's clock: who or what, and whether it went wrong.
type RaidMark struct {
	ClockMS int64  `json:"clockMS"`
	EndMS   int64  `json:"endMS,omitempty"`
	Text    string `json:"text"`
	Bad     bool   `json:"bad,omitempty"`
}
